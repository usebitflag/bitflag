// Generates resources/css/theme.generated.css from the reviewed BitFlag design inputs in design/bitflag.
//   node scripts/tokens/generate-theme.mjs           write the file
//   node scripts/tokens/generate-theme.mjs --check   fail if it is stale or a contrast pair fails
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { contrast, mix } from './color.mjs';

const root = fileURLToPath(new URL('../..', import.meta.url));
const paths = {
  tokens: `${root}design/bitflag/tokens.json`,
  components: `${root}design/bitflag/components.json`,
  output: `${root}resources/css/theme.generated.css`,
};

const sha256 = (text) => createHash('sha256').update(text).digest('hex');

/** Resolves one theme's colour roles, derived mixes and semantic roles to concrete hex values. */
export function resolveTheme(theme) {
  const colors = { ...theme.colors };

  for (const [name, spec] of Object.entries(theme.mix ?? {})) {
    const fg = colors[spec.color] ?? spec.color;
    const bg = colors[spec.into];
    if (!bg) throw new Error(`Mix "${name}" refers to unknown role "${spec.into}"`);
    colors[name] = mix(fg, bg, spec.percent);
  }

  for (const [name, spec] of Object.entries(theme.semantic ?? {})) {
    colors[name] = spec.solid;
    colors[`${name}-text`] = spec.text;
    colors[`${name}-subtle`] = mix(spec.solid, colors.surface, spec.subtle);
    colors[`${name}-border`] = mix(spec.solid, colors.surface, spec.border);
  }

  return colors;
}

export function checkContrast(themeName, colors, pairs) {
  const failures = [];
  for (const { fg, bg, min } of pairs) {
    if (!colors[fg] || !colors[bg]) {
      failures.push(`${themeName}: unknown role in pair ${fg} on ${bg}`);
      continue;
    }
    const ratio = contrast(colors[fg], colors[bg]);
    if (ratio < min) {
      failures.push(
        `${themeName}: ${fg} (${colors[fg]}) on ${bg} (${colors[bg]}) is ${ratio.toFixed(2)}:1, needs ${min}:1`,
      );
    }
  }
  return failures;
}

function declarations(entries, indent = '  ') {
  return entries.map(([name, value]) => `${indent}${name}: ${value};`).join('\n');
}

export function generate({ tokens, components }) {
  const radius = tokens.radius;
  const failures = [];
  const resolved = {};

  for (const [themeName, theme] of Object.entries(tokens.themes)) {
    resolved[themeName] = resolveTheme(theme);
    failures.push(...checkContrast(themeName, resolved[themeName], tokens.contrast));
  }

  const roleNames = Object.keys(resolved.light);
  for (const [themeName, colors] of Object.entries(resolved)) {
    const missing = roleNames.filter((role) => !(role in colors));
    if (missing.length) failures.push(`${themeName}: missing roles ${missing.join(', ')}`);
  }

  const themeBlock = (themeName) => {
    const theme = tokens.themes[themeName];
    const entries = [
      ...Object.entries(resolved[themeName]).map(([role, value]) => [`--bf-${role}`, value]),
      ...Object.entries(theme.shadows).map(([size, value]) => [`--bf-shadow-${size}`, value]),
      ['color-scheme', theme.colorScheme],
    ];
    return declarations(entries);
  };

  const gradient = `linear-gradient(${tokens.gradient.angle}, ${tokens.gradient.stops
    .map((stop) => `${stop.color} ${stop.at}`)
    .join(', ')})`;

  const componentEntries = Object.entries(components).flatMap(([component, props]) =>
    Object.entries(props).map(([prop, value]) => {
      const resolvedValue =
        prop === 'radius'
          ? `var(--radius-${value})`
          : prop === 'font-size'
            ? `var(--text-${value})`
            : value;
      return [`--bf-${component}-${prop}`, resolvedValue];
    }),
  );

  const layoutEntries = Object.entries(tokens.layout).map(([name, value]) => [
    `--bf-${name}-width`.replace('topbar-width', 'topbar-height'),
    value,
  ]);

  const themeMappings = roleNames.map((role) => [`--color-${role}`, `var(--bf-${role})`]);

  const css = `/* Generated by scripts/tokens/generate-theme.mjs. Do not edit; run \`npm run tokens\`.
 * input hashes (sha256)
 * theme ${sha256(JSON.stringify(tokens))}
 * components ${sha256(JSON.stringify(components))}
 */

/* Light is the base theme. Dark applies when data-theme="dark" is set on the root element. */
:root {
${themeBlock('light')}
${declarations([
  ['--bf-gradient', gradient],
  ...layoutEntries,
  ...componentEntries,
  ...Object.entries(tokens.fontWeights).map(([name, value]) => [
    `--bf-weight-${name}`,
    String(value),
  ]),
])}
}

:root[data-theme='dark'] {
${themeBlock('dark')}
}

@theme inline {
  --color-*: initial;
${declarations(themeMappings)}
${declarations(Object.entries(tokens.fonts).map(([name, value]) => [`--font-${name}`, value]))}
${declarations(Object.entries(tokens.fontSizes).map(([name, value]) => [`--text-${name}`, value]))}
${declarations(Object.entries(radius).map(([name, value]) => [`--radius-${name}`, value]))}
${declarations(Object.keys(tokens.themes.light.shadows).map((size) => [`--shadow-${size}`, `var(--bf-shadow-${size})`]))}
}
`;

  return { css, failures };
}

function readInputs() {
  return {
    tokens: JSON.parse(readFileSync(paths.tokens, 'utf8')),
    components: JSON.parse(readFileSync(paths.components, 'utf8')),
  };
}

function main() {
  const check = process.argv.includes('--check');
  const inputs = readInputs();
  const problems = [];

  const { css, failures } = generate(inputs);
  problems.push(...failures);

  if (check) {
    const current = existsSync(paths.output) ? readFileSync(paths.output, 'utf8') : '';
    if (current !== css)
      problems.push(
        'resources/css/theme.generated.css is stale. Run `npm run tokens` and commit the result.',
      );
  } else if (failures.length === 0) {
    writeFileSync(paths.output, css);
    console.log('Wrote resources/css/theme.generated.css');
  }

  if (problems.length) {
    console.error(problems.join('\n'));
    process.exit(1);
  }
  if (check) console.log('Theme is current and every contrast pair passes.');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
